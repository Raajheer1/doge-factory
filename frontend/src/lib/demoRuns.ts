// Approvals and replays live in this browser only.
const KEY = 'doge-demo-runs';
type DemoState = { approvals: Record<string, string>; replays: Record<string, { base: string; query: string; startedAt: number }> };
function load(): DemoState { try { return JSON.parse(localStorage.getItem(KEY) || '') as DemoState; } catch { return { approvals: {}, replays: {} }; } }
function save(s: DemoState) { try { localStorage.setItem(KEY, JSON.stringify(s)); } catch { /* optional */ } }

const REPLAY_MS = { retrieving: 2500, auditing: 6000 };

function materialize(id: string): Run | null {
  const state = load();
  const replay = state.replays[id];
  const base = SEED.find((r) => r.id === (replay?.base ?? id));
  if (!base) return null;
  const run: Run = structuredClone(base);
  run.id = id;
  if (state.approvals[id]) run.selected_finding_id = state.approvals[id];
  if (replay) {
    // Replay the analysis so the Barriers progress screen can be seen.
    run.query = replay.query;
    run.created_at = new Date(replay.startedAt).toISOString();
    const elapsed = Date.now() - replay.startedAt;
    if (elapsed < REPLAY_MS.retrieving) Object.assign(run, { status: 'running', stage: 'retrieving', retrieved: 0, reviewed: 0, findings: [] });
    else if (elapsed < REPLAY_MS.auditing) Object.assign(run, { status: 'running', stage: 'auditing_and_drafting', reviewed: Math.floor(run.retrieved / 2), findings: [] });
  }
  return run;
}

export function listDemoRuns(): Run[] {
  const replays = Object.keys(load().replays);
  return [...replays, ...SEED.map((r) => r.id)].map(materialize).filter((r): r is Run => !!r);
}
export const getDemoRun = (id: string) => materialize(id);

export function approveDemo(runId: string, findingId: string) {
  const s = load();
  s.approvals[runId] = findingId;
  save(s);
}

/** Start a replay of the closest demo problem for a pitch (used when the analysis API is offline). */
export function startDemoReplay(query: string): string {
  const base = /tenant|income|hous|rent|hud|voucher/i.test(query) ? 'demo-hud-paystubs' : 'demo-ky-esign';
  const id = `${DEMO_PREFIX}replay-${Date.now().toString(36)}`;
  const s = load();
  s.replays[id] = { base, query, startedAt: Date.now() };
  save(s);
  return id;
}
